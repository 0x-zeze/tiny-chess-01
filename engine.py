# Tiny chess engine, written from scratch for tiny-chess-01.
# 0x88 board, negamax + alpha-beta + iterative deepening, quiescence,
# transposition table, killer moves, MVV-LVA ordering, incremental
# material + piece-square evaluation. Fixed node budget per move:
# fully deterministic, no clock, no randomness in move choice.
import json, os, sys, urllib.request, urllib.error

VAL = [0, 100, 320, 330, 500, 900, 0]
KN = [-33, -31, -18, -14, 14, 18, 31, 33]
KG = [-17, -16, -15, -1, 1, 15, 16, 17]
BD = [-17, -15, 15, 17]
RD = [-16, -1, 1, 16]
QD = BD + RD
SQ = [r * 16 + f for r in range(8) for f in range(8)]
KP = [15] * 128
KP[0] = 13; KP[7] = 14; KP[4] = 12; KP[112] = 7; KP[119] = 11; KP[116] = 3
EPF = 1 << 17; CSF = 1 << 18; DBF = 1 << 19
INF = 1000000; MATE = 100000
OPEN = 6400

# Piece-square tables, generated by formula (white's view, square a1=0).
def _pst():
    T = [[0] * 64 for _ in range(7)]
    for r in range(8):
        for f in range(8):
            i = r * 8 + f
            c = min(f, 7 - f) + min(r, 7 - r)
            T[1][i] = [0, 0, 5, 10, 18, 30, 45, 0][r] + ([0, 0, 0, 8, 12, 8, 4, 0][r] if f in (3, 4) else 0)
            T[2][i] = 6 * c - 18
            T[3][i] = 4 * c - 6
            T[4][i] = (12 if r == 6 else 0) + (4 if r == 0 and f in (3, 4) else 0)
            T[5][i] = 2 * c - 4
            T[6][i] = [18, 24, 8, 0, 0, 8, 24, 18][f] if r == 0 else max(-40, -12 * r)
    return T
PST = _pst()
EGK = [8 * (min(f, 7 - f) + min(r, 7 - r)) - 20 for r in range(8) for f in range(8)]
MGK = PST[6]

def rel(sq, white):
    r = sq >> 4; f = sq & 7
    return r * 8 + f if white else (7 - r) * 8 + f

def pv(pc, sq):
    t = pc if pc > 0 else -pc
    v = VAL[t] + PST[t][rel(sq, pc > 0)]
    return v if pc > 0 else -v

# Zobrist keys from a fixed xorshift stream (deterministic).
_s = [88172645463325252]
def _nx():
    x = _s[0]
    x ^= (x << 13) & 0xFFFFFFFFFFFFFFFF; x ^= x >> 7; x ^= (x << 17) & 0xFFFFFFFFFFFFFFFF
    _s[0] = x & 0xFFFFFFFFFFFFFFFF
    return _s[0]
Z = [[_nx() for _ in range(128)] for _ in range(13)]
ZS = _nx(); ZC = [_nx() for _ in range(16)]; ZE = [_nx() for _ in range(8)]

# Mutable position state (globals for speed).
B = [0] * 128; S = 1; C = 0; E = -1; HM = 0
V = 0; NP = 0; KW = 4; KB = 116; BW = 0; BB = 0; H = 0
U = []; PATH = []; GH = set()
T = {}; KL = [0] * 256; HH = [0] * 8192
ND = 0; CAP = 60000; AB = 0; DEPTH = 0

def init(fen):
    global B, S, C, E, HM, V, NP, KW, KB, BW, BB, H
    B = [0] * 128; V = 0; NP = 0; BW = 0; BB = 0; H = 0
    p = fen.split()
    for r, row in enumerate(p[0].split('/')):
        rank = 7 - r; f = 0
        for ch in row:
            if ch.isdigit():
                f += int(ch); continue
            pc = 'PNBRQK'.index(ch.upper()) + 1
            if ch.islower(): pc = -pc
            sq = rank * 16 + f; B[sq] = pc; V += pv(pc, sq)
            if abs(pc) == 6:
                if pc > 0: KW = sq
                else: KB = sq
            elif abs(pc) == 3:
                if pc > 0: BW += 1
                else: BB += 1
            elif abs(pc) != 1:
                NP += VAL[abs(pc)]
            f += 1
    S = 1 if p[1] == 'w' else -1
    C = 0
    for ch in p[2]:
        C |= {'K': 1, 'Q': 2, 'k': 4, 'q': 8}.get(ch, 0)
    E = -1 if p[3] == '-' else (int(p[3][1]) - 1) * 16 + (ord(p[3][0]) - 97)
    HM = int(p[4]) if len(p) > 4 else 0
    for sq in SQ:
        pc = B[sq]
        if pc: H ^= Z[pc + 6][sq]
    if S < 0: H ^= ZS
    H ^= ZC[C]
    if E >= 0: H ^= ZE[E & 7]

def _att(to, by, gone):
    # Least valuable attacker of colour `by` on square `to`, or None.
    if by > 0:
        for s in (to - 15, to - 17):
            if not s & 0x88 and B[s] == 1 and s not in gone: return (100, s)
    else:
        for s in (to + 15, to + 17):
            if not s & 0x88 and B[s] == -1 and s not in gone: return (100, s)
    for d in KN:
        s = to + d
        if not s & 0x88 and s not in gone and B[s] == (2 if by > 0 else -2): return (320, s)
    bv = 100000; bs = -1
    for d in KG:
        s = to + d
        if not s & 0x88 and s not in gone and B[s] == (6 if by > 0 else -6): bs = s
    for ds, tys in ((BD, (3, 5)), (RD, (4, 5))):
        for d in ds:
            s = to + d
            while not s & 0x88:
                if s in gone:
                    s += d; continue
                pc = B[s]
                if pc:
                    if (pc > 0) == (by > 0) and abs(pc) in tys and VAL[abs(pc)] < bv:
                        bv = VAL[abs(pc)]; bs = s
                    break
                s += d
    return (bv, bs) if bs >= 0 else None

def see(to, mv):
    # Net material gain for the side to move capturing on `to` with a piece
    # worth `mv` (static exchange evaluation, optimal stopping).
    tg = B[to]
    v = 100 if tg == 0 else VAL[abs(tg)]
    gone = set(); d = [v]; on = mv; side = -S; i = 0
    while True:
        r = _att(to, side, gone)
        if r is None: break
        av, sq = r
        d.append(d[-1] - on if i % 2 == 0 else d[-1] + on)
        if av >= 100000: break  # king captured: the exchange ends
        gone.add(sq); on = av; side = -side; i += 1
    val = d[-1]
    for k in range(len(d) - 1, 1, -1):
        if k % 2 == 1:
            if d[k - 1] > val: val = d[k - 1]
        elif d[k - 1] < val: val = d[k - 1]
    return val

def attacked(sq, by):
    # by: 1 white, -1 black. Is sq attacked by a piece of colour `by`?
    if by > 0:
        if not (sq - 15) & 0x88 and B[sq - 15] == 1: return True
        if not (sq - 17) & 0x88 and B[sq - 17] == 1: return True
    else:
        if not (sq + 15) & 0x88 and B[sq + 15] == -1: return True
        if not (sq + 17) & 0x88 and B[sq + 17] == -1: return True
    for d in KN:
        t = sq + d
        if not t & 0x88 and B[t] == (2 if by > 0 else -2): return True
    for d in KG:
        t = sq + d
        if not t & 0x88 and B[t] == (6 if by > 0 else -6): return True
    for d in BD:
        t = sq + d
        while not t & 0x88:
            pc = B[t]
            if pc:
                if pc == (3 if by > 0 else -3) or pc == (5 if by > 0 else -5): return True
                break
            t += d
    for d in RD:
        t = sq + d
        while not t & 0x88:
            pc = B[t]
            if pc:
                if pc == (4 if by > 0 else -4) or pc == (5 if by > 0 else -5): return True
                break
            t += d
    return False

def in_check():
    return attacked(KW if S > 0 else KB, -S)

def gen(co=False):
    ms = []
    for sq in SQ:
        pc = B[sq]
        if not pc or (pc > 0) != (S > 0): continue
        t = pc if pc > 0 else -pc
        if t == 1:
            d = 16 if S > 0 else -16
            rk = sq >> 4; pr = (rk == 6) if S > 0 else (rk == 1)
            sr = 1 if S > 0 else 6
            one = sq + d
            if B[one] == 0:
                if pr:
                    for q in (5, 4, 3, 2): ms.append(sq | one << 7 | q << 14)
                elif not co:
                    ms.append(sq | one << 7)
                    two = one + d
                    if rk == sr and B[two] == 0: ms.append(sq | two << 7 | DBF)
            for dd in (d - 1, d + 1):
                to = sq + dd
                if to & 0x88: continue
                tg = B[to]
                if tg and (tg > 0) != (S > 0):
                    if pr:
                        for q in (5, 4, 3, 2): ms.append(sq | to << 7 | q << 14)
                    else: ms.append(sq | to << 7)
                elif to == E and E >= 0:
                    ms.append(sq | to << 7 | EPF)
        elif t == 2 or t == 6:
            for d in KN if t == 2 else KG:
                to = sq + d
                if to & 0x88: continue
                tg = B[to]
                if not tg:
                    if not co: ms.append(sq | to << 7)
                elif (tg > 0) != (S > 0): ms.append(sq | to << 7)
            if t == 6 and not co:
                base = 0 if S > 0 else 112
                if (KW if S > 0 else KB) == base + 4 and not attacked(base + 4, -S):
                    if (C & (1 if S > 0 else 4)) and B[base + 5] == 0 and B[base + 6] == 0 and not attacked(base + 5, -S) and not attacked(base + 6, -S):
                        ms.append(base + 4 | base + 6 << 7 | CSF)
                    if (C & (2 if S > 0 else 8)) and B[base + 3] == 0 and B[base + 2] == 0 and B[base + 1] == 0 and not attacked(base + 3, -S) and not attacked(base + 2, -S):
                        ms.append(base + 4 | base + 2 << 7 | CSF)
        else:
            for d in BD if t == 3 else RD if t == 4 else QD:
                to = sq + d
                while not to & 0x88:
                    tg = B[to]
                    if not tg:
                        if not co: ms.append(sq | to << 7)
                    else:
                        if (tg > 0) != (S > 0): ms.append(sq | to << 7)
                        break
                    to += d
    return ms

def make(m):
    global S, C, E, HM, V, NP, KW, KB, BW, BB, H
    f = m & 127; t = (m >> 7) & 127; pr = (m >> 14) & 7
    pc = B[f]; us = S
    cap = B[t]; cs = t
    if m & EPF:
        cs = t - 16 if us > 0 else t + 16; cap = B[cs]
    U.append((m, cap, cs, C, E, HM, V, NP, H, KW, KB, BW, BB))
    H ^= Z[pc + 6][f]
    if cap: H ^= Z[cap + 6][cs]
    H ^= ZC[C]
    if E >= 0: H ^= ZE[E & 7]
    V -= pv(pc, f); B[f] = 0
    if cap:
        V -= pv(cap, cs); B[cs] = 0
        if abs(cap) == 3:
            if cap > 0: BW -= 1
            else: BB -= 1
        elif abs(cap) != 1: NP -= VAL[abs(cap)]
    npc = pc
    if pr:
        npc = pr if us > 0 else -pr
        NP += VAL[pr]
        if pr == 3:
            if us > 0: BW += 1
            else: BB += 1
    B[t] = npc; V += pv(npc, t)
    H ^= Z[npc + 6][t]
    if abs(pc) == 6:
        if us > 0: KW = t
        else: KB = t
    if m & CSF:
        base = 0 if us > 0 else 112
        rf, rt = (base + 7, base + 5) if t == base + 6 else (base, base + 3)
        rp = B[rf]; B[rf] = 0; B[rt] = rp
        V -= pv(rp, rf); V += pv(rp, rt)
        H ^= Z[rp + 6][rf] ^ Z[rp + 6][rt]
    C &= KP[f] & KP[t]
    E = (f + t) // 2 if m & DBF else -1
    HM = 0 if abs(pc) == 1 or cap else HM + 1
    H ^= ZC[C]
    if E >= 0: H ^= ZE[E & 7]
    H ^= ZS
    S = -S
    if attacked(KW if us > 0 else KB, -us):
        unmake(); return False
    return True

def unmake():
    global S, C, E, HM, V, NP, KW, KB, BW, BB, H
    m, cap, cs, C, E, HM, V, NP, H, KW, KB, BW, BB = U.pop()
    f = m & 127; t = (m >> 7) & 127; pr = (m >> 14) & 7
    pc = B[t]
    B[t] = 0
    if m & CSF:
        base = 0 if pc > 0 else 112
        rf, rt = (base + 7, base + 5) if t == base + 6 else (base, base + 3)
        rp = B[rt]; B[rt] = 0; B[rf] = rp
    if cap: B[cs] = cap
    B[f] = (1 if pc > 0 else -1) if pr else pc
    S = -S

def ev():
    s = V
    if BW >= 2: s += 30
    if BB >= 2: s -= 30
    k = OPEN - NP
    if k:
        s += ((EGK[rel(KW, True)] - MGK[rel(KW, True)]) - (EGK[rel(KB, False)] - MGK[rel(KB, False)])) * k // OPEN
    return s * S

def order(ms, tt, ply):
    def sc(m):
        if m == tt: return 1000000
        to = (m >> 7) & 127; tg = B[to]; s = 0
        if tg or (m & EPF):
            vic = 1 if m & EPF else (tg if tg > 0 else -tg)
            s = 100000 + 10 * VAL[vic] - VAL[abs(B[m & 127])]
        if m >> 14: s += 200000 + VAL[(m >> 14) & 7]
        elif s == 0:
            if m == KL[ply * 2]: s = 50000
            elif m == KL[ply * 2 + 1]: s = 40000
            else:
                f = m & 127
                h = HH[(0 if S > 0 else 4096) + ((f >> 4) * 8 + (f & 7)) * 64 + (to >> 4) * 8 + (to & 7)] // 4
                s = h if h < 30000 else 30000
        return s
    ms.sort(key=sc, reverse=True)

def qs(a, b, ply, qd=0):
    global ND, AB
    ND += 1
    if ND >= CAP:
        AB = 1; return 0
    if ply >= 120: return ev()
    chk = in_check()
    if not chk:
        st = ev()
        if st >= b: return st
        best = st
        if st > a: a = st
    else:
        best = -MATE - 1
    if chk and qd >= 4:
        # Deep in quiescence: only captures; a mate this deep is approximated.
        ms = gen(True)
        if not ms: return ev()
    else:
        ms = gen(not chk)
    order(ms, 0, ply)
    legal = 0
    for m in ms:
        if not chk and not (m >> 14):
            to = (m >> 7) & 127; tg = B[to]
            vic = 1 if m & EPF else (abs(tg) if tg else 0)
            if vic and best + VAL[vic] + 200 < a: continue  # delta pruning
            if vic and see(to, VAL[abs(B[m & 127])]) < 0: continue  # losing capture
        if not make(m): continue
        legal += 1
        s = -qs(-b, -a, ply + 1, qd + 1)
        unmake()
        if AB: return 0
        if s > best: best = s
        if s >= b: return s
        if s > a: a = s
    if chk and legal == 0: return -MATE + ply if qd < 4 else ev()
    return best

def srch(d, a, b, ply):
    global ND, AB, S, C, E, HM, H
    if ply > 0 and (HM >= 100 or H in PATH or H in GH): return 0
    if d <= 0: return qs(a, b, ply)
    ND += 1
    if ND >= CAP:
        AB = 1; return 0
    e = T.get(H); ttm = 0
    if e:
        ed, ef, es, em = e; ttm = em
        if ed >= d:
            s = es
            if s > MATE - 200: s -= ply
            elif s < -MATE + 200: s += ply
            if ef == 1: return s
            if ef == 2 and s >= b: return s
            if ef == 3 and s <= a: return s
    chk = in_check()
    # Null-move pruning: pass and search shallower; a good reply proves beta.
    if d >= 3 and not chk and NP > 0:
        st = ev()
        if st >= b:
            oE, oHM, oH = E, HM, H
            if oE >= 0: H ^= ZE[oE & 7]
            E = -1; HM = oHM + 1; H ^= ZS; S = -S
            PATH.append(oH)
            s = -srch(d - 3, -b, -b + 1, ply + 1)
            PATH.pop()
            E, HM, H, S = oE, oHM, oH, -S
            if AB: return 0
            if s >= b: return s
    # Futility margin for quiet moves near the leaves.
    fut = 0
    if d <= 2 and not chk:
        fut = ev() + 150 * d
    ms = gen(False)
    order(ms, ttm, ply)
    a0 = a; best = -MATE - 1; bm = 0; legal = 0
    for i, m in enumerate(ms):
        to = (m >> 7) & 127
        cap = bool(B[to] or (m & EPF))
        rh = H
        if fut and not cap and not (m >> 14) and m != ttm and legal > 0 and fut <= a:
            continue
        if not make(m): continue
        legal += 1
        PATH.append(rh)
        if i >= 4 and d >= 3 and not chk and not cap and not (m >> 14) and m != KL[ply * 2] and m != KL[ply * 2 + 1]:
            s = -srch(d - 2, -b, -a, ply + 1)
            if not AB and s > a:
                s = -srch(d - 1, -b, -a, ply + 1)
        else:
            s = -srch(d - 1, -b, -a, ply + 1)
        PATH.pop()
        unmake()
        if AB: return 0
        if s > best: best = s; bm = m
        if s > a: a = s
        if a >= b:
            if not cap and not (m >> 14):
                if KL[ply * 2] != m:
                    KL[ply * 2 + 1] = KL[ply * 2]; KL[ply * 2] = m
                f = m & 127
                HH[(0 if S > 0 else 4096) + ((f >> 4) * 8 + (f & 7)) * 64 + (to >> 4) * 8 + (to & 7)] += d * d
            break
    if legal == 0: return -MATE + ply if in_check() else 0
    fl = 3 if best <= a0 else 2 if best >= b else 1
    st = best + ply if best > MATE - 200 else best - ply if best < -MATE + 200 else best
    T[H] = (d, fl, st, bm)
    return best

def legal_moves():
    out = []
    for m in gen(False):
        if make(m):
            out.append(m); unmake()
    return out

def best_move():
    global ND, AB, DEPTH
    ms = legal_moves()
    if not ms: return None
    if len(ms) == 1: return ms[0]
    order(ms, 0, 0)
    sc = {}
    best = ms[0]; ND = 0; DEPTH = 0
    for d in range(1, 13):
        AB = 0
        a = -INF; cur = None; cs = -INF
        for m in ms:
            rh = H
            make(m); PATH.append(rh)
            s = -srch(d - 1, -INF, -a, 1)
            PATH.pop(); unmake()
            if AB: break
            sc[m] = s
            if s > cs: cs = s; cur = m
            if s > a: a = s
        if AB: break
        if cur is not None:
            best = cur; DEPTH = d
            ms.sort(key=lambda m: sc.get(m, 0), reverse=True)
            if cs >= MATE - 200: break
    return best

def uci(m):
    f = m & 127; t = (m >> 7) & 127; pr = (m >> 14) & 7
    s = chr(97 + (f & 7)) + str((f >> 4) + 1) + chr(97 + (t & 7)) + str((t >> 4) + 1)
    return s + ('nbrq'[pr - 2] if pr else '')

def move_from_uci(u):
    f = (int(u[1]) - 1) * 16 + (ord(u[0]) - 97)
    t = (int(u[3]) - 1) * 16 + (ord(u[2]) - 97)
    pr = 'nbrq'.index(u[4]) + 2 if len(u) == 5 else 0
    for m in gen(False):
        if (m & 127) == f and ((m >> 7) & 127) == t and ((m >> 14) & 7) == pr:
            return m
    return None

START = "rnbqkbnr/pppppppp/8/8/8/8/PPPPPPPP/RNBQKBNR w KQkq - 0 1"

def history_hashes(moves):
    """Hashes of positions before the current one, replayed from start."""
    global GH
    GH = set()
    init(START)
    for i, u in enumerate(moves):
        m = move_from_uci(u)
        if m is None: break
        make(m)
        if i < len(moves) - 1: GH.add(H)

# ---- env driver ----
ENV_URL = os.environ.get("MAKEFUN_ENV_URL")

def post(path, body):
    req = urllib.request.Request(ENV_URL + path, data=json.dumps(body).encode(),
                                 headers={"content-type": "application/json"})
    try:
        with urllib.request.urlopen(req) as res:
            return json.load(res)
    except urllib.error.HTTPError as e:
        sys.exit(f"{path}: HTTP {e.code} {e.read().decode(errors='replace')}")

def main():
    if not ENV_URL: sys.exit("MAKEFUN_ENV_URL is not set")
    while True:
        g = post("/game", {})
        if g["status"] == "done": break
        T.clear(); KL[:] = [0] * 256
        while g["status"] == "your_move":
            history_hashes(g["moves"])
            init(g["fen"])
            m = best_move()
            u = uci(m) if m is not None else None
            if u not in (g["legal_moves"] or []):
                u = g["legal_moves"][0]
            g = post("/move", {"game": g["game"], "move": u})
        print(f"game {g['game']}: {g['outcome']} by {g['reason']}", file=sys.stderr)
    print(f"done: {g.get('wins')} won, {g.get('draws')} drawn, {g.get('losses')} lost", file=sys.stderr)

if __name__ == "__main__":
    main()
